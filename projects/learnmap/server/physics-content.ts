const bi = (s: string) => ({ uk: s, en: s });
export function physicsQuestion(id: string, level: number) {
  const task = physicsBank[id]?.[level - 1];
  if (!task) return null;
  const shift = (level + id.length) % 4,
    choices = [task.right, ...task.wrong];
  const options = [...choices.slice(shift), ...choices.slice(0, shift)];
  return {
    id: `physics-v4-${id}-${level}`,
    skill_id: id,
    difficulty: level,
    prompt: bi(task.prompt),
    options,
    answer: options.indexOf(task.right),
    reasoning: bi(task.reason),
    hints: [
      bi('Визнач тіло або систему тіл і межі моделі.'),
      bi('Познач відомі величини, напрямки та одиниці.'),
      bi('З’ясуй, що зберігається та які взаємодії суттєві.'),
      bi('Перевір розмірність і правдоподібність результату.'),
      bi(task.reason),
    ],
    presentation: {
      cognitive_key: cognitiveDemand[level - 1].key,
      graph: task.graph || null,
      circuit:
        id === 'mixed-circuits' && level <= 4
          ? level === 2 || level === 3
            ? ['2 Ом', '6 Ом', '3 Ом']
            : ['R₁', 'R₂', 'R₃']
          : null,
    },
  };
}
