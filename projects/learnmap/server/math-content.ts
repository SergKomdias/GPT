const local = (text: string) => ({ uk: text, en: text });
export function mathQuestion(id: string, n: number) {
  const rows = mathBank[id];
  if (!rows) return null;
  const index = n % 8;
  const level = index < 5 ? index : index - 4;
  const [prompt, right, ...rest] = index < 5 ? rows[index] : mathPracticeBank[id][index - 5];
  const explanation = rest[3];
  const choices = [right, ...rest.slice(0, 3)];
  const shift = level % 4;
  const options = [...choices.slice(shift), ...choices.slice(0, shift)];
  const rule = mathDefinitions.find((d) => d[0] === id)![5];
  return {
    id: `math-v3-${id}-${index < 5 ? level + 1 : 'practice-' + (index - 4)}`,
    skill_id: id,
    difficulty: level + 1,
    prompt: local(prompt),
    options,
    answer: options.indexOf(right),
    reasoning: local(explanation),
    hints: [
      local('Визнач відомі дані, невідоме та всі обмеження.'),
      local(rule),
      local('Запиши математичну модель і виконай рівносильні перетворення.'),
      local('Перевір допустимість результату та відкинь варіанти, що суперечать умові.'),
      local(explanation),
    ],
  };
}
